/** Provider-neutral contracts; implemented services remain independent of Alex runtime. */
import type { ModelMessage, ModelProvider, ModelRouter } from '../providers.ts'

export const AI_CONTRACT_VERSION = 1 as const
export type Support = 'supported' | 'unsupported' | 'unknown'
export type Modality = 'text' | 'image' | 'audio' | 'video' | 'embedding' | (string & {})
export type JsonValue = null | boolean | number | string | readonly JsonValue[] | { readonly [key: string]: JsonValue }

/** Evidence applies to metadata, never to a secret or an unsanitized API response. */
export interface Evidence {
  source: 'provider-api' | 'official-documentation' | 'operator' | 'inference-response'
  observedAt: string // ISO 8601 UTC
  reference: string | null // sanitized reference; never a credential-bearing URL
}

/** Vendor/gateway definition, independent of individual accounts and models. */
export interface ProviderDefinition {
  id: string
  name: string
  adapterId: string // extensible adapter registry key, not a closed vendor list
  discovery: Support
  accountMetadata: Support
}

/** Safe metadata: plaintext secrets must never be members of this contract. */
export interface ProviderConnection {
  id: string // globally unique connection ID, including across vendors
  providerId: string
  label: string
  baseUrl: string // validated endpoint with no embedded credentials/query tokens
  scope: { account: string | null; project: string | null; region: string | null }
  enabled: boolean
  revision: number // optimistic concurrency / configuration version
  credentials: { state: 'missing' | 'configured' | 'not-required'; revision: number }
  health: {
    authentication: 'unknown' | 'accepted' | 'rejected'
    discovery: 'never-tested' | 'succeeded' | 'failed' | 'unsupported'
    inference: 'never-tested' | 'succeeded' | 'failed'
    checkedAt: string | null
  }
}

/** Server-only opaque reference; the future secret store resolves it internally. */
export interface ServerConnection {
  connection: ProviderConnection
  credentialRef: string | null
}

export interface ModelCapabilities {
  input: readonly Modality[] | null // null = unknown, [] = explicitly no modalities
  output: readonly Modality[] | null
  tools: Support
  streaming: Support
  structuredOutput: Support
  systemInstructions: Support
}

/** Native IDs are opaque, case-sensitive and must never be rewritten. */
export interface ModelDescriptor {
  nativeModelId: string
  displayName: string
  capabilities: ModelCapabilities
  contextTokens: number | null
  maxOutputTokens: number | null
  evidence: Evidence
  extensions: Readonly<Record<string, JsonValue>> // sanitized provider-specific data
}

export interface ModelRouteRef {
  connectionId: string
  nativeModelId: string
  upstreamEndpointId: string | null // null = default/automatic gateway routing
}

/** A selectable access route; duplicate names and cross-provider IDs stay distinct. */
export interface ModelRoute {
  id: string // generated by modelRouteKey(); not a display name
  ref: ModelRouteRef
  providerId: string
  protocol: string // e.g. openai-chat, anthropic-messages; not a capability claim
  connectionRevision: number
  model: Omit<ModelDescriptor, 'nativeModelId'> // ref holds the single authoritative ID
  access: {
    state: 'unknown' | 'listed' | 'account-listed' | 'verified' | 'denied' | 'unavailable'
    evidence: Evidence | null
  }
  lifecycle: 'active' | 'deprecated' | 'removed' | 'unknown'
}

/** Decimal strings avoid silently rounding money; null always means unknown. */
export interface PriceComponent {
  dimension: string // input/output/cached tokens, request, image, audio, etc.
  amount: string
  currency: string
  unit: string
  per: string // decimal billing denominator, e.g. "1000000" tokens
}
export interface Pricing {
  components: readonly PriceComponent[]
  completeness: 'complete' | 'partial' | 'unknown'
  evidence: Evidence | null
  freeAccess: {
    kind: 'verified-zero-price' | 'conditional-free-tier' | 'credits' | 'paid' | 'local-no-api-fee' | 'unknown'
    eligibility: 'verified' | 'ineligible' | 'unknown'
    conditions: readonly string[]
    evidence: Evidence | null
  }
}
export interface LimitObservation {
  dimension: string // requests, tokens, credit, spend, concurrency, etc.
  scope: 'account' | 'connection' | 'key' | 'project' | 'region' | 'model'
  scopeId: string // opaque non-secret scope ID; never an API key
  limit: string | null // null is unknown; not implicitly unlimited
  remaining: string | null
  unit: string
  resetsAt: string | null
  evidence: Evidence
}
export interface UsageObservation {
  requestId: string
  routeId: string
  agentId: string | null
  inputTokens: number | null
  outputTokens: number | null
  cost: { amount: string; currency: string; basis: 'reported' | 'estimated' } | null
  actualModelId: string | null
  actualUpstreamId: string | null
  evidence: Evidence
}

export interface CatalogEntry {
  verification?: import('./verification-store.ts').Verification | null // explicit probe history, never discovery
  route: ModelRoute
  pricing: Pricing
  limits: readonly LimitObservation[]
  firstSeenAt: string
  lastSeenAt: string
}
export interface DiscoveryPage {
  models: readonly ModelDescriptor[]
  nextCursor: string | null // adapter-defined cursor; null ends enumeration
  visibility: 'public' | 'account-filtered' | 'local' | 'unknown'
}
export interface CatalogRefresh {
  id: string
  connectionId: string
  connectionRevision: number
  state: 'pending' | 'running' | 'complete' | 'partial' | 'failed' | 'cancelled' | 'unsupported'
  cursor: string | null
  startedAt: string | null
  completedAt: string | null
  errorCode: string | null // stable sanitized code, not a raw provider error
}
export interface CatalogQuery {
  search?: string
  connectionIds?: readonly string[]
  providerIds?: readonly string[]
  outputModality?: Modality
  freeAccessKinds?: readonly Pricing['freeAccess']['kind'][]
  cursor?: string
  pageSize?: number // page size is not a total catalog/model-count ceiling
}
export interface CatalogPage {
  entries: readonly CatalogEntry[]
  nextCursor: string | null
  total: number | null
  snapshotId: string // stable paging snapshot; avoid mixing refresh versions
}
export interface ModelCatalog {
  search(query: CatalogQuery): Promise<CatalogPage>
  getRoute(routeId: string): Promise<CatalogEntry | null>
  refresh(connectionId: string): Promise<CatalogRefresh>
}

/** Rich Phase 2 interface. Secret resolution stays behind adapter implementation. */
export interface ProviderAdapter {
  readonly definition: ProviderDefinition
  discover(connection: ServerConnection, cursor: string | null, signal?: AbortSignal): Promise<DiscoveryPage>
  complete(request: InferenceRequest, connection: ServerConnection, signal?: AbortSignal): Promise<InferenceResult>
  observeLimits?(connection: ServerConnection, signal?: AbortSignal): Promise<readonly LimitObservation[]>
}
export interface InferenceRequest {
  route: ModelRoute
  agentId: string
  messages: readonly ModelMessage[] // reuse Alex's provider-neutral text contract
  maxOutputTokens?: number
}
export interface InferenceResult {
  text: string
  usage: UsageObservation | null // unavailable is not zero usage/cost
}
export interface AgentModelAssignment {
  agentId: string
  routeId: string
  revision: number
  requirements: {
    input: readonly Modality[]
    output: readonly Modality[]
    tools: boolean
    streaming: boolean
    systemInstructions: boolean
  }
}
/** Explicit assignments only. No autonomous selection or fallback/Nexus policy. */
export interface AgentModelResolver {
  resolve(assignment: AgentModelAssignment): Promise<ModelRoute>
}

/** Compatibility seam only: the existing classes are neither replaced nor wired. */
export interface LegacyProviderBinding {
  readonly route: ModelRouteRef
  readonly provider: ModelProvider // includes existing HttpProvider instances
  readonly router: ModelRouter
}
